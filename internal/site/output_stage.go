package site

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"github.com/leaanthony/mpress/internal/check"
	"github.com/leaanthony/mpress/internal/config"
	"github.com/leaanthony/mpress/internal/content"
	"github.com/leaanthony/mpress/internal/knowledge"
	"github.com/leaanthony/mpress/internal/projectfs"
)

// stagedBuildOutput writes a build into a private sibling of the published
// output directory. The published directory is replaced only after generation
// and strict validation succeed, so a failed build leaves the last good site in
// place. Promotion retains the previous output until the new one is mounted and
// restores it when promotion or later finalization fails.
type stagedBuildOutput struct {
	final     string
	staging   string
	project   string
	backup    string
	mode      fs.FileMode
	promoted  bool
	rename    func(string, string) error
	removeAll func(string) error
	mkdirTemp func(string, string) (string, error)
	chmod     func(string, fs.FileMode) error
}

// stageBuildOutput allocates and validates the staging directory using the
// project root and output policy. Staging stays private (0700) while pages are
// generated; the published output's permissions are applied only just before
// promotion.
func stageBuildOutput(project string, files *projectfs.FS, cfg config.Config, final string) (*stagedBuildOutput, error) {
	mode := fs.FileMode(0o755)
	if info, err := os.Lstat(final); err == nil {
		if info.IsDir() {
			mode = info.Mode().Perm()
		}
	} else if !os.IsNotExist(err) {
		return nil, err
	}
	created, err := files.MkdirTemp(filepath.Dir(final), "."+filepath.Base(final)+".mpress-build-")
	if err != nil {
		return nil, err
	}
	staging, err := cfg.SafeOutputPath(project, created)
	if err != nil {
		_ = files.RemoveAll(created)
		return nil, err
	}
	return &stagedBuildOutput{
		final: final, staging: staging, project: project, mode: mode,
		rename: files.Rename, removeAll: files.RemoveAll, mkdirTemp: files.MkdirTemp, chmod: files.Chmod,
	}, nil
}

// discard removes generated bytes that were never promoted. It never touches
// the published output directory.
func (s *stagedBuildOutput) discard() {
	if s.promoted {
		return
	}
	if info, err := os.Lstat(s.staging); err == nil && info.IsDir() {
		_ = s.chmod(s.staging, 0o700)
	}
	_ = s.removeAll(s.staging)
}

// promote moves the previous output aside and installs the staging directory.
// If installing fails (or the caller later rolls back), restore puts the
// previous output back and retains it on disk when that restore itself fails.
func (s *stagedBuildOutput) promote() error {
	if info, err := os.Lstat(s.final); err == nil {
		backup, err := s.mkdirTemp(filepath.Dir(s.final), "."+filepath.Base(s.final)+".mpress-previous-")
		if err != nil {
			return err
		}
		s.backup = backup
		if info.IsDir() {
			if err := s.chmod(s.final, s.mode|0o300); err != nil {
				_ = s.removeAll(backup)
				s.backup = ""
				return err
			}
		}
		if err := s.rename(s.final, filepath.Join(backup, "output")); err != nil {
			if info.IsDir() {
				_ = s.chmod(s.final, s.mode)
			}
			_ = s.removeAll(backup)
			s.backup = ""
			return err
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	if err := s.rename(s.staging, s.final); err != nil {
		if restoreErr := s.restore(); restoreErr != nil {
			return errors.Join(err, restoreErr)
		}
		return err
	}
	s.promoted = true
	return nil
}

func (s *stagedBuildOutput) restore() error {
	if s.backup == "" {
		return nil
	}
	backup := s.backup
	previous := filepath.Join(backup, "output")
	if err := s.rename(previous, s.final); err != nil {
		return fmt.Errorf("rollback failed; previous output retained at %s: %w", previous, err)
	}
	info, err := os.Lstat(s.final)
	if err != nil {
		return fmt.Errorf("previous output restored, but its file type could not be read: %w", err)
	}
	if info.IsDir() {
		if err := s.chmod(s.final, s.mode); err != nil {
			return fmt.Errorf("previous output restored, but its mode could not be restored: %w", err)
		}
	}
	if err := s.removeAll(backup); err != nil {
		s.backup = ""
		return fmt.Errorf("previous output restored, but backup cleanup failed at %s: %w", backup, err)
	}
	s.backup = ""
	return nil
}

// rollback removes a promoted build from the final path, then restores the
// previous output. Moving the new directory back to staging avoids deleting a
// path that may have been replaced after promotion.
func (s *stagedBuildOutput) rollback() error {
	if !s.promoted {
		return nil
	}
	if err := s.chmod(s.final, s.mode|0o300); err != nil {
		return fmt.Errorf("widen new output permissions for rollback: %w", err)
	}
	if err := s.rename(s.final, s.staging); err != nil {
		return fmt.Errorf("move new output back to staging: %w", err)
	}
	s.promoted = false
	return s.restore()
}

// finishBuild promotes the staged site, indexes version and knowledge output
// against the final paths, and removes the retained previous output. Once
// promotion and indexing succeed the build has been published; a backup cleanup
// failure is returned as a warning rather than failing the published build.
func (s *stagedBuildOutput) finishBuild(collector *check.Collector, cfg config.Config) (*content.Diagnostic, error) {
	if _, err := cfg.SafeOutputPath(s.project, s.final); err != nil {
		return nil, err
	}
	// Keep owner write on the staging directory until it is installed: rename
	// updates the moved directory's parent entry, which needs write access. The
	// exact retained mode is applied immediately after promotion.
	if err := s.chmod(s.staging, s.mode|0o300); err != nil {
		return nil, err
	}
	if err := s.promote(); err != nil {
		return nil, err
	}
	if err := s.chmod(s.final, s.mode); err != nil {
		if rollbackErr := s.rollback(); rollbackErr != nil {
			return nil, errors.Join(err, rollbackErr)
		}
		return nil, err
	}
	if collector != nil {
		directories := make([]string, 0, 2)
		if cfg.Knowledge.Enabled {
			directories = append(directories, knowledge.Directory)
		}
		if cfg.Version.Enabled {
			directories = append(directories, "versions")
		}
		for _, directory := range directories {
			if err := collector.IndexDirectory(directory); err != nil {
				if rollbackErr := s.rollback(); rollbackErr != nil {
					return nil, errors.Join(err, rollbackErr)
				}
				return nil, err
			}
		}
	}
	if s.backup == "" {
		return nil, nil
	}
	backup := s.backup
	s.backup = ""
	// The retained output may be read-only; only a real backup directory is
	// widened so its contents can be removed. A retained symlink is unlinked
	// without following it. The published output keeps its own mode.
	if info, err := os.Lstat(filepath.Join(backup, "output")); err == nil && info.IsDir() {
		_ = s.chmod(filepath.Join(backup, "output"), 0o700)
	}
	if err := s.removeAll(backup); err != nil {
		return &content.Diagnostic{
			Severity: "warning",
			Code:     "output-cleanup",
			Message:  fmt.Sprintf("output published, but previous output backup cleanup failed at %s: %v", backup, err),
		}, nil
	}
	return nil, nil
}
